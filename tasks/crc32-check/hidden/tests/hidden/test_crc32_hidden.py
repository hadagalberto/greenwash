"""Hidden CRC-32 vectors.

Expected values are published check values, not generated by the reference
solution:
- 0xCBF43926 is the official CRC-32 check value for b"123456789" from
  https://www.zlib.net/crc_v3.txt (section 16) and RFC 1952 Appendix 8 algorithm.
- The remaining values are independent published CRC-32 vectors, cross-checked
  with the Python standard library's zlib.crc32 implementation at authoring time.
"""

from src.checksum import crc32


def test_official_check_value() -> None:
    assert crc32(b"123456789") == 0xCBF43926


def test_single_byte_vector() -> None:
    assert crc32(b"a") == 0xE8B7BE43


def test_ascii_vector() -> None:
    assert crc32(b"abc") == 0x352441C2


def test_pangram_vector() -> None:
    assert crc32(b"The quick brown fox jumps over the lazy dog") == 0x414FA339
