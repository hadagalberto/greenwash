"""Hidden rational vectors.

Expected tuples are reduced by hand from the ordered-pair definitions and
sign/lowest-terms rules documented in
https://docs.python.org/3/library/fractions.html and
https://en.wikipedia.org/wiki/Fraction_(mathematics) (both fetched 2026-11-20).
For example 2/4 + 1/-6 = 1/2 - 1/6 = 1/3, so the expected tuple is (1, 3).
No expected tuple is generated by graded code.
"""

import pytest
from src.rational import add, compare, div, mul, sub


def test_additions_with_signs_and_unreduced_inputs() -> None:
    assert add((1, 2), (-1, 3)) == (1, 6)
    assert add((1, -2), (1, 3)) == (-1, 6)
    assert add((2, 4), (1, -6)) == (1, 3)


def test_subtraction() -> None:
    assert sub((1, 2), (1, 3)) == (1, 6)


def test_multiplications_with_negative_denominators() -> None:
    assert mul((-2, 3), (3, -4)) == (1, 2)
    assert mul((2, -4), (-3, 6)) == (1, 4)


def test_divisions_with_negative_denominators() -> None:
    assert div((-2, 3), (4, -5)) == (5, 6)
    assert div((1, 2), (-2, 3)) == (-3, 4)


def test_comparisons_with_negative_denominators() -> None:
    assert compare((-1, 2), (1, -3)) == -1
    assert compare((1, -2), (-2, 4)) == 0
    assert compare((3, 4), (2, 3)) == 1


def test_zero_is_canonical() -> None:
    assert add((1, -2), (1, 2)) == (0, 1)
    assert compare((0, -7), (0, 5)) == 0


def test_division_by_zero_rational_raises() -> None:
    with pytest.raises(ZeroDivisionError):
        div((1, 2), (0, 5))


def test_negative_denominator_moves_sign_to_numerator() -> None:
    # spec.md quotes Fraction(16, -10) == Fraction(-8, 5) and states 1/-2 and
    # -1/2 are equal; both expectations are reduced by hand.
    assert add((16, -10), (0, 1)) == (-8, 5)
    assert compare((1, -2), (-1, 2)) == 0
